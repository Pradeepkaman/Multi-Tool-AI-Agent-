"""Autonomous Multi-Tool AI Agent implementing the ReAct reasoning chain.

Thought -> Action -> Observation -> Final Answer
"""

import json
from typing import List, Dict, Any, Optional, Callable
from langchain_core.messages import (
    BaseMessage,
    SystemMessage,
    HumanMessage,
    AIMessage,
    ToolMessage,
)
from rich.console import Console
from rich.panel import Panel
from rich.text import Text

from src.tools import ALL_TOOLS, TOOLS_BY_NAME

console = Console()

SYSTEM_PROMPT = """You are an autonomous AI research and problem-solving agent equipped with specialized tools.
Your goal is to solve the user's query by breaking it down logically and invoking tools when needed.

Available Tools:
1. `web_search`: Search DuckDuckGo for real-time online data, facts, statistics, benchmarks, and definitions.
2. `calculator`: Perform accurate math calculations, arithmetic, and formula evaluations.
3. `read_local_file`: Read contents of local files (notes, text, reports, markdown, data).

Execution Guidelines:
- Before taking any action, reason carefully about what information you have and what you still need.
- If the question asks about data in a local file, read the local file first.
- If calculations are required (e.g., percentages, growth rates, sums), always use the `calculator` tool to avoid hallucinating arithmetic.
- If real-time or external facts are needed, use `web_search`.
- You can chain multiple tools sequentially across multiple steps to solve compound questions.
- Once you have sufficient information to answer the question completely, formulate a concise, well-structured final answer.
"""


class AutonomousAgent:
    """Multi-tool autonomous agent running a visible ReAct loop."""

    def __init__(
        self,
        llm: Any,
        tools: Optional[List[Any]] = None,
        max_iterations: int = 10,
        verbose: bool = True,
    ):
        self.raw_llm = llm
        self.tools = tools or ALL_TOOLS
        self.tools_map = {tool.name: tool for tool in self.tools}
        self.model_with_tools = self.raw_llm.bind_tools(self.tools)
        self.max_iterations = max_iterations
        self.verbose = verbose

    def _log_thought(self, thought: str):
        if not self.verbose or not thought.strip():
            return
        console.print()
        console.print(Panel(thought.strip(), title="[bold magenta]🤔 Thought[/bold magenta]", border_style="magenta"))

    def _log_action(self, tool_name: str, args: Dict[str, Any]):
        if not self.verbose:
            return
        args_str = json.dumps(args, indent=2) if isinstance(args, dict) else str(args)
        content = f"[bold cyan]Tool:[/bold cyan] {tool_name}\n[bold cyan]Input:[/bold cyan] {args_str}"
        console.print(Panel(content, title="[bold cyan]⚡ Action[/bold cyan]", border_style="cyan"))

    def _log_observation(self, observation: str):
        if not self.verbose:
            return
        # Display preview if observation is very long
        display_obs = observation if len(observation) <= 1500 else observation[:1500] + "\n... [truncated]"
        console.print(Panel(display_obs.strip(), title="[bold green]👁️ Observation[/bold green]", border_style="green"))

    def _log_final_answer(self, answer: str):
        console.print()
        console.print(Panel(answer.strip(), title="[bold yellow]🎯 Final Answer[/bold yellow]", border_style="yellow"))

    def run(self, query: str) -> str:
        """Executes the agent loop on a user query.

        Args:
            query: The user prompt or compound research query.

        Returns:
            The final answer string generated by the agent.
        """
        messages: List[BaseMessage] = [
            SystemMessage(content=SYSTEM_PROMPT),
            HumanMessage(content=query),
        ]

        iteration = 0
        final_answer = ""

        with console.status("[bold green]Agent thinking...", spinner="dots"):
            pass

        while iteration < self.max_iterations:
            iteration += 1

            # Invoke the model bound with tools
            response = self.model_with_tools.invoke(messages)
            messages.append(response)

            # Check for text / thoughts emitted by model
            content = response.content
            if isinstance(content, list):
                # If content blocks (multimodal or structured text)
                text_blocks = [c.get("text", "") for c in content if isinstance(c, dict) and "text" in c]
                thought_text = "\n".join(text_blocks).strip()
            else:
                thought_text = str(content).strip() if content else ""

            # Check if tools were called
            tool_calls = getattr(response, "tool_calls", []) or []

            if thought_text and tool_calls:
                # Model produced thought before tool calls
                self._log_thought(thought_text)

            if not tool_calls:
                # No more tools called; this is the final answer!
                final_answer = thought_text or "No response generated."
                self._log_final_answer(final_answer)
                return final_answer

            # Execute each invoked tool
            for tc in tool_calls:
                tool_name = tc.get("name")
                tool_args = tc.get("args", {})
                call_id = tc.get("id")

                self._log_action(tool_name, tool_args)

                # Execute tool safely
                if tool_name in self.tools_map:
                    target_tool = self.tools_map[tool_name]
                    try:
                        observation = target_tool.invoke(tool_args)
                        observation_str = str(observation)
                    except Exception as err:
                        observation_str = f"Error executing tool '{tool_name}': {str(err)}"
                else:
                    observation_str = f"Error: Tool '{tool_name}' is not recognized. Available tools: {list(self.tools_map.keys())}"

                self._log_observation(observation_str)

                # Feed observation back into message history
                messages.append(
                    ToolMessage(
                        content=observation_str,
                        tool_call_id=call_id or f"call_{iteration}",
                    )
                )

        # Exceeded max iterations
        fallback_msg = f"Agent reached maximum iterations ({self.max_iterations}) without concluding."
        self._log_final_answer(fallback_msg)
        return fallback_msg
